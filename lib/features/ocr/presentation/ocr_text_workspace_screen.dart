      ),
      decoration: const BoxDecoration(
        color: AppColors.navyElevated,
        borderRadius: BorderRadius.all(Radius.circular(AppRadius.large)),
      ),
      child: const Row(
        crossAxisAlignment: CrossAxisAlignment.start,
