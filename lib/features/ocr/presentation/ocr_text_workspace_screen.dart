import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

enum _OcrPrototypeState { ready, processing, result }

class OcrTextWorkspaceScreen extends StatefulWidget {
  const OcrTextWorkspaceScreen({
    required this.document,
    required this.currentPage,
    super.key,
  });

  final DocumentSummary document;
  final int currentPage;

  @override
  State<OcrTextWorkspaceScreen> createState() =>
      _OcrTextWorkspaceScreenState();
}

class _OcrTextWorkspaceScreenState extends State<OcrTextWorkspaceScreen> {
  static const List<String> _languages = <String>[
    'English',
    'Spanish',
    'French',
    'German',
  ];

  late final TextEditingController _textController;
  _OcrPrototypeState _state = _OcrPrototypeState.ready;
  String _language = _languages.first;

  @override
  void initState() {
    super.initState();
    _textController = TextEditingController(text: _mockText());
  }

  @override
  void dispose() {
    _textController.dispose();
    super.dispose();
  }

  String _mockText() {
    return '''${widget.document.title}

Page ${widget.currentPage}

Meeting summary
• Review the ClearScan interface direction.
• Keep document processing private and offline-first.
• Validate export and OCR workflows before adding dependencies.

This is editable sample text generated by the UI prototype.''';
  }

  Future<void> _runMockOcr() async {
    if (_state == _OcrPrototypeState.processing) {
      return;
    }

    setState(() => _state = _OcrPrototypeState.processing);
    await Future<void>.delayed(const Duration(milliseconds: 700));
    if (!mounted) {
      return;
    }
    setState(() => _state = _OcrPrototypeState.result);
  }

  void _resetPrototype() {
    _textController.text = _mockText();
    setState(() => _state = _OcrPrototypeState.ready);
  }

  Future<void> _copyMockText() async {
    await Clipboard.setData(ClipboardData(text: _textController.text));
    if (!mounted) {
      return;
    }
    _showMessage('Editable mock text copied to the clipboard.');
  }

  void _showMessage(String message) {
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(
        SnackBar(
          content: Text(message),
          behavior: SnackBarBehavior.floating,
        ),
      );
  }

  @override
  Widget build(BuildContext context) {
    return Theme(
      data: AppTheme.workspaceDark,
      child: Scaffold(
        key: const Key('ocr-text-workspace-screen'),
        appBar: AppBar(
          leading: IconButton(
            key: const Key('close-ocr-text-workspace'),
            onPressed: () => Navigator.of(context).pop(),
            icon: const Icon(Icons.arrow_back_rounded),
            tooltip: 'Back to document',
          ),
          title: const Text('OCR Text'),
          actions: <Widget>[
            if (_state == _OcrPrototypeState.result)
              IconButton(
                key: const Key('reset-ocr-prototype'),
                onPressed: _resetPrototype,
                icon: const Icon(Icons.refresh_rounded),
                tooltip: 'Reset mock OCR',
              ),
          ],
        ),
        body: SafeArea(
          top: false,
          child: Column(
            children: <Widget>[
              const _OcrPrototypeNotice(),
              const SizedBox(height: AppSpacing.md),
              Padding(
                padding: const EdgeInsets.symmetric(horizontal: AppSpacing.md),
                child: DropdownButtonFormField<String>(
                  key: const Key('ocr-language-selector'),
                  initialValue: _language,
                  decoration: const InputDecoration(
                    labelText: 'Recognition language',
                    prefixIcon: Icon(Icons.language_rounded),
                  ),
                  dropdownColor: AppColors.navyElevated,
                  items: _languages
                      .map(
                        (String language) => DropdownMenuItem<String>(
                          value: language,
                          child: Text(language),
                        ),
                      )
                      .toList(),
                  onChanged: (String? value) {
                    if (value != null) {
                      setState(() => _language = value);
                    }
                  },
                ),
              ),
              const SizedBox(height: AppSpacing.md),
              Expanded(child: _buildWorkspace()),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildWorkspace() {
    return switch (_state) {
      _OcrPrototypeState.ready => _OcrReadyState(
          documentTitle: widget.document.title,
          pageNumber: widget.currentPage,
          language: _language,
          onRun: () => unawaited(_runMockOcr()),
        ),
      _OcrPrototypeState.processing => const _OcrProcessingState(),
      _OcrPrototypeState.result => _OcrResultState(
          controller: _textController,
          language: _language,
          onCopy: () => unawaited(_copyMockText()),
          onShare: () => _showMessage(
            'Text sharing is a placeholder until platform sharing is integrated.',
          ),
        ),
    };
  }
}

